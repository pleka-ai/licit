  entry_id::TEXT AS entry_id,
  @texto(title) AS title,
  @texto(summary) AS summary,
  @texto(link) AS link,
  updated::TIMESTAMPTZ AS updated,
  feed_type::TEXT AS feed_type,
  @texto(contract_folder_id) AS contract_folder_id,
  status_code::TEXT AS status_code,
  @texto(organo_ref) AS organo_ref,
  @texto(name) AS name,
  type_code::TEXT AS type_code,
  sub_type_code::TEXT AS sub_type_code,
  estimated_overall_contract_amount::DOUBLE AS estimated_overall_contract_amount,
  total_amount::DOUBLE AS total_amount,
  tax_exclusive_amount::DOUBLE AS tax_exclusive_amount,
  currency_id::TEXT AS currency_id,
  @texto(nuts_code) AS nuts_code,
  @texto(country_subentity) AS country_subentity,
  duration_measure::DOUBLE AS duration_measure,
  duration_unit_code::TEXT AS duration_unit_code,
  @fecha(planned_start_date) AS planned_start_date,
  @fecha(planned_end_date) AS planned_end_date,
  @texto(option_validity_description) AS option_validity_description,
  @texto(options_description) AS options_description,
  mix_contract_indicator::BOOLEAN AS mix_contract_indicator,
  procedure_code::TEXT AS procedure_code,
  urgency_code::TEXT AS urgency_code,
  submission_method_code::TEXT AS submission_method_code,
  @fecha(submission_deadline_date) AS submission_deadline_date,
  submission_deadline_time::TEXT AS submission_deadline_time,
  @texto(submission_deadline_description) AS submission_deadline_description,
