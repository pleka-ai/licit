  @texto(procurement_legislation_id) AS procurement_legislation_id,
  variant_constraint_indicator::BOOLEAN AS variant_constraint_indicator,
  @texto(price_revision_formula) AS price_revision_formula,
  funding_program_code::TEXT AS funding_program_code,
  @texto(funding_program_name) AS funding_program_name,
  @texto(funding_program_description) AS funding_program_description,
