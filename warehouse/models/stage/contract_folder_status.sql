  document_availability_end_time::TEXT AS document_availability_end_time,
  contracting_system_code::TEXT AS contracting_system_code,
  part_presentation_code::TEXT AS part_presentation_code,
  auction_constraint_indicator::BOOLEAN AS auction_constraint_indicator,
  max_lot_presentation_quantity::INT AS max_lot_presentation_quantity,
  max_tenderer_awarded_lots_qty::INT AS max_tenderer_awarded_lots_qty,
  @texto(lots_combination_rights) AS lots_combination_rights,
  over_threshold_indicator::BOOLEAN AS over_threshold_indicator,
  @fecha(participation_request_end_date) AS participation_request_end_date,
